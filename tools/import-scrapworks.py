"""Imports the Scrapworks UI pack into the game.

Copies the 1x/2x PNGs unmodified (all geometry in the pack's manifest refers to
the full sprite canvases) and generates web/src/ui/scrapworks.css from the
manifest: one `.sw-<id>` class per sprite with its natural size, label-safe
rect and slice insets as CSS variables, plus a 1x/2x `image-set()`.
Derives two tinted stars the pack doesn't ship (earned / unearned).

    python3 tools/import-scrapworks.py <dir with 1x/ and 2x/> <manifest.json>
"""
import json
import shutil
import sys
from pathlib import Path

from PIL import Image, ImageEnhance

ROOT = Path(__file__).resolve().parent.parent
SRC, MANIFEST = Path(sys.argv[1]), Path(sys.argv[2])
OUT = ROOT / "assets/ui/scrapworks"
CSS = ROOT / "web/src/ui/scrapworks.css"


def tint(im: Image.Image, rgb: tuple[int, int, int]) -> Image.Image:
    """Multiplies a cream icon by a colour, keeping its shading and alpha."""
    r, g, b, a = im.split()
    lum = Image.merge("RGB", (r, g, b)).convert("L")
    out = Image.merge("RGB", [lum.point(lambda v, c=c: v * c // 255) for c in rgb])
    out.putalpha(a)
    return out


INK = (64, 54, 34)  # #403622, the pack's dark text colour


def is_cream(im: Image.Image) -> bool:
    """True for the pack's monochrome cream icons (not the coloured ones like coins and gems)."""
    raw = im.tobytes()
    px = [raw[i:i + 4] for i in range(0, len(raw), 4) if raw[i + 3] > 200]
    if not px:
        return False
    sat = sum(max(p[:3]) - min(p[:3]) for p in px) / len(px)
    light = sum(sum(p[:3]) / 3 for p in px) / len(px)
    return sat < 70 and light > 180


def url(scale: str, cat: str, name: str) -> str:
    return f"url('/ui/scrapworks/{scale}/{cat}/{name}.png')"


def image_set(cat: str, name: str) -> str:
    return f"image-set({url('1x', cat, name)} 1x, {url('2x', cat, name)} 2x)"


def main() -> None:
    manifest = json.loads(MANIFEST.read_text())
    assets = {a["id"]: a for a in manifest["assets"]}
    for scale in ("1x", "2x"):
        for cat in ("controls", "decor", "icons", "panels"):
            dst = OUT / scale / cat
            dst.mkdir(parents=True, exist_ok=True)
            for f in (SRC / scale / cat).glob("*.png"):
                shutil.copyfile(f, dst / f.name)
        # Ink-tinted copies of the cream icons, for use on paper (the pack's recipes tint them dark brown).
        for f in sorted((SRC / scale / "icons").glob("*.png")):
            im = Image.open(f).convert("RGBA")
            if is_cream(im):
                tint(im, INK).save(OUT / scale / "icons" / f"{f.stem}_ink.png", optimize=True)
        star = Image.open(SRC / scale / "icons/star.png").convert("RGBA")
        tint(star, (255, 196, 64)).save(OUT / scale / "icons/star_gold.png", optimize=True)
        ImageEnhance.Brightness(star).enhance(0.35).save(OUT / scale / "icons/star_dim.png", optimize=True)
    for f in sorted((OUT / "1x/icons").glob("*_ink.png")):
        assets[f.stem] = {**assets[f.stem[:-4]], "id": f.stem}
    assets["star_gold"] = {**assets["star"], "id": "star_gold"}
    assets["star_dim"] = {**assets["star"], "id": "star_dim"}
    (ROOT / "assets/ui/scrapworks/LICENSE-NOTE.txt").write_text(
        "Scrapworks UI pack (project-owned). Imported by tools/import-scrapworks.py.\n")

    lines = [
        "/* Generated by tools/import-scrapworks.py from the Scrapworks manifest. Do not edit. */",
        "/* --w/--h: natural 1x size; --sx/--sy/--sw/--sh: label-safe rect; --il/--it/--ir/--ib: slice insets (1x px). */",
    ]
    for aid in sorted(assets):
        a = assets[aid]
        cat = a["category"]
        s = a["label_safe_rect"]
        props = [f"--w: {a['width']}", f"--h: {a['height']}", f"--sx: {s['x']}", f"--sy: {s['y']}", f"--sw: {s['w']}", f"--sh: {s['h']}"]
        if a.get("slice_insets"):
            i = a["slice_insets"]
            props += [f"--il: {i['left']}", f"--it: {i['top']}", f"--ir: {i['right']}", f"--ib: {i['bottom']}"]
        props.append(f"--img: {image_set(cat, aid)}")
        lines.append(f".sw-{aid} {{ {'; '.join(props)}; }}")
    # Button families: all four state images on one class, for :hover/:active/:disabled.
    for fam in sorted({a["family"] for a in assets.values() if a.get("family") and a.get("state") == "normal" and a.get("slice_insets")}):
        props = [f"--img-{st}: {image_set('controls', f'{fam}_{st}')}" for st in ("normal", "hover", "pressed", "disabled")]
        lines.append(f".swb-{fam} {{ {'; '.join(props)}; }}")
    CSS.write_text("\n".join(lines) + "\n")
    print(f"copied {len(assets)} sprites; wrote {CSS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
